import { useState } from 'react';
import toast from 'react-hot-toast';
import { Check, Eye, RefreshCw } from 'lucide-react';
import { intelligenceService as api, errMsg } from '../../services/intelligenceService';
import useIntelQuery from '../../hooks/useIntelQuery';
import { PageHeader, Panel, Async, Table, Pager, Badge, severityTone, statusTone, pretty, fmtDateTime, inputCls, btnGhost } from '../../components/intelligence/ui';

export default function LowStockAlerts() {
  const [f, setF] = useState({ status: '', type: '', severity: '', page: 1 });
  const q = useIntelQuery(() => api.alerts({ ...f, limit: 15 }), [f.status, f.type, f.severity, f.page], { interval: 20000 });
  const act = async (fn, msg) => { try { await fn(); toast.success(msg); q.reload(); } catch (e) { toast.error(errMsg(e)); } };
  const scan = () => act(() => api.runJob('lowStockScan'), 'Scan complete');
  const sel = (k, opts, label) => (
    <select className={inputCls} value={f[k]} onChange={(e) => setF({ ...f, [k]: e.target.value, page: 1 })}>
      <option value="">{label}</option>{opts.map((o) => <option key={o} value={o}>{pretty(o)}</option>)}</select>);

  return (
    <div>
      <PageHeader title="Low-Stock Alerts" subtitle="Generated by Change Streams on every stock change and a 15-minute scheduled scan. Alerts auto-resolve when stock recovers."
        actions={<button className={btnGhost} onClick={scan}><RefreshCw size={14} />Scan now</button>} />
      <Panel actions={<div className="flex flex-wrap gap-2">
        {sel('status', ['OPEN', 'ACKNOWLEDGED', 'RESOLVED'], 'Active (open + acknowledged)')}
        {sel('type', ['LOW_STOCK', 'OUT_OF_STOCK', 'PREDICTED_STOCKOUT', 'SUPPLIER_OVERDUE', 'ANOMALY'], 'All types')}
        {sel('severity', ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW'], 'All severities')}</div>}>
        <Async q={q} empty="No alerts match these filters">
          <Table rows={q.data || []} columns={[
            { key: 'severity', header: 'Severity', render: (r) => <Badge tone={severityTone[r.severity]}>{r.severity}</Badge> },
            { key: 'type', header: 'Type', render: (r) => pretty(r.type) },
            { key: 'message', header: 'Alert', render: (r) => <div className="max-w-md"><p>{r.message}</p>
              <p className="text-xs text-slate-400">{r.warehouse?.name ? `${r.warehouse.name} · ` : ''}triggered {r.occurrences}×</p></div> },
            { key: 'currentStock', header: 'Stock / threshold', render: (r) => (r.currentStock != null ? `${r.currentStock} / ${r.threshold ?? '—'}` : '—') },
            { key: 'lastTriggeredAt', header: 'Last seen', render: (r) => fmtDateTime(r.lastTriggeredAt) },
            { key: 'status', header: 'Status', render: (r) => <Badge tone={statusTone[r.status]}>{pretty(r.status)}</Badge> },
            { key: 'actions', header: '', render: (r) => r.isActive && (
              <div className="flex gap-1">
                {r.status === 'OPEN' && <button className={btnGhost} title="Acknowledge" onClick={() => act(() => api.ackAlert(r._id), 'Acknowledged')}><Eye size={14} /></button>}
                <button className={btnGhost} title="Resolve" onClick={() => act(() => api.resolveAlert(r._id), 'Resolved')}><Check size={14} /></button>
              </div>) },
          ]} />
          <Pager meta={q.meta} onChange={(page) => setF({ ...f, page })} />
        </Async>
      </Panel>
    </div>
  );
}